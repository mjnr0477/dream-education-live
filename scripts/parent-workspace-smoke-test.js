const fs = require("fs");
const assert = require("assert");
const index = fs.readFileSync("public/index.html", "utf8");
const workspace = fs.readFileSync("public/frontend-workspace.js", "utf8");
const parent = fs.readFileSync("public/parent-workspace.js", "utf8");
const css = fs.readFileSync("public/parent-workspace.css", "utf8");
const server = fs.readFileSync("server.js", "utf8");
assert(index.includes("/parent-workspace.js"), "Parent workspace script must be loaded.");
assert(index.includes("/parent-workspace.css"), "Parent workspace styles must be loaded.");
assert(workspace.includes("DreamParentWorkspace.open"), "Existing workspace must hand parent accounts to the dedicated portal.");
for (const label of ["My children", "Lessons & home learning", "AI Parent Guide", "Achievements", "Teachers & meetings"]) assert(parent.includes(label), "Missing parent section: " + label);
assert(parent.includes("/api/v1/role/parent/intelligence"), "Parent portal must reuse existing role intelligence.");
assert(parent.includes("/api/v1/learning/resources?"), "Parent portal must use connected learning resource discovery.");
assert(parent.includes("/api/v1/learning/notes"), "Parent guide must use the existing notes engine.");
assert(parent.includes("/api/v1/parent/children/"), "Parent lessons must use the permission-checked parent endpoint.");
assert(server.includes("/api/v1/parent/children/:learner_id/assigned-lessons"), "Server must expose the secure parent lesson view.");
assert(server.includes("parent child lesson access denied"), "Parent child lesson endpoint must enforce relationship authorization.");
assert(css.includes(".parent-workspace-nav") && css.includes("@media(max-width:640px)"), "Parent workspace must be responsive.");
console.log("Real parent workspace smoke test passed.");