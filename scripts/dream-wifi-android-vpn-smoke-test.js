"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "..", "android", "dream-wifi-vpn");
const manifest = fs.readFileSync(path.join(root, "app/src/main/AndroidManifest.xml"), "utf8");
const activity = fs.readFileSync(path.join(root, "app/src/main/java/com/dreameducation/wifi/MainActivity.java"), "utf8");
const service = fs.readFileSync(path.join(root, "app/src/main/java/com/dreameducation/wifi/DreamVpnService.java"), "utf8");
const workflow = fs.readFileSync(path.join(__dirname, "..", ".github/workflows/dream-wifi-android-vpn.yml"), "utf8");
const readme = fs.readFileSync(path.join(root, "README.md"), "utf8");
const proxy = fs.readFileSync(path.join(__dirname, "dream-wifi-proxy-client.js"), "utf8");
const source = fs.readFileSync(path.join(__dirname, "dream-wifi-source-agent.js"), "utf8");
const relay = fs.readFileSync(path.join(__dirname, "..", "product", "dream_wifi_tunnel_engine.js"), "utf8");
assert.match(manifest, /android\.net\.VpnService/);
assert.match(manifest, /BIND_VPN_SERVICE/);
assert.match(service, /TProxyStartService/);
assert.match(service, /addRoute\("0\.0\.0\.0",0\)/);
assert.match(service, /addRoute\("::",0\)/);
assert.match(service, /addDisallowedApplication\("com\.termux"\)/);
assert.match(service, /addDnsServer\("198\.18\.0\.2"\)/);
assert.match(service, /127\.0\.0\.1:1080/);
assert.match(activity, /VpnService\.prepare/);
assert.match(workflow, /9b2c2320b26046b307abd6ddb5f102b2ccd1d4a4/);
assert.match(readme, /not yet validated on a physical device/);
assert.match(proxy, /atyp === 4/);
assert.match(proxy, /buffer.readUInt16BE\(4 \+ index \* 2\)/);
assert.match(proxy, /message.type === "udp-data"/);
assert.match(proxy, /message.type === "udp-send"/);
assert.match(source, /dgram.createSocket/);
assert.match(source, /resolvePublicHost\(host\)/);
assert.match(relay, /MAX_UDP_ASSOCIATIONS_PER_OWNER/);
assert.match(relay, /message.type === 'udp-send'/);
assert.doesNotMatch(service, /DREAM_WIFI_SOURCE_TOKEN|DREAM_WIFI_OWNER_ACCESS_TOKEN/);
console.log("Dream Wi-Fi Android VPN project smoke test passed.");
