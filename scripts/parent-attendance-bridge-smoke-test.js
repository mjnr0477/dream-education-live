"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const root = path.join(__dirname, "..");
const server = fs.readFileSync(path.join(root, "server.js"), "utf8");
const parent = fs.readFileSync(path.join(root, "public/parent-workspace.js"), "utf8");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
assert.match(server, /app\.get\("\/api\/v1\/parent\/attendance"/);
const start = server.indexOf('app.get("/api/v1/parent/attendance"');
const end = server.indexOf('app.get("/api/v1/school/attendance"', start);
const route = server.slice(start, end);
assert.match(route, /getAuthenticatedAccount\(req\)/);
assert.match(route, /auth\.account\.role.*parent/);
assert.match(route, /status: "active", type: "parent_learner", role: "parent", id: parentId/);
assert.match(route, /connection\.from_role === "parent"/);
assert.match(route, /connection\.to_role === "learner"/);
assert.match(route, /\["present", "absent", "late", "excused"\]/);
assert.doesNotMatch(route, /note: record\.note/);
assert.match(route, /attendance\.slice\(0, 300\)/);
assert.match(parent, /\/api\/v1\/parent\/attendance/);
assert.match(parent, /state\.attendance\.slice\(0, 60\)/);
assert.match(parent, /Only attendance status and date/);
assert.match(pkg.scripts.test, /parent-attendance-bridge-smoke-test\.js/);
execFileSync(process.execPath, ["--check", path.join(root, "server.js")]);
execFileSync(process.execPath, ["--check", path.join(root, "public/parent-workspace.js")]);
console.log("Parent attendance bridge smoke test passed.");
