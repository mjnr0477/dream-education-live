/* Dream Education Media Studio — calls the server; API keys never enter the browser. */
(function () {
  "use strict";

  function getAuthToken() {
    try {
      const auth = JSON.parse(localStorage.getItem("dream_education_auth") || "null");
      return auth?.session?.access_token || "";
    } catch (_) {
      return "";
    }
  }

  function setPanelText(id, value) {
    const element = document.getElementById(id);
    if (element) element.textContent = value;
  }

  function appendText(parent, tag, text, className) {
    const node = document.createElement(tag);
    node.textContent = text;
    if (className) node.className = className;
    parent.appendChild(node);
    return node;
  }

  function findOutputText(value) {
    if (typeof value === "string") return value;
    if (!value || typeof value !== "object") return "";
    const direct = [value.content, value.text, value.output_text, value.message, value.translation];
    for (const item of direct) {
      if (typeof item === "string" && item.trim()) return item;
    }
    if (Array.isArray(value.choices)) {
      const content = value.choices[0]?.message?.content || value.choices[0]?.text;
      if (typeof content === "string") return content;
    }
    if (Array.isArray(value.data) && value.data[0]) {
      const nested = findOutputText(value.data[0]);
      if (nested) return nested;
    }
    return "";
  }

  function findMediaUrl(value, depth) {
    if (!value || depth > 5) return "";
    if (typeof value === "string") {
      return /^(https:\/\/|data:(image|audio)\/)/i.test(value) ? value : "";
    }
    if (Array.isArray(value)) {
      for (const item of value) {
        const found = findMediaUrl(item, depth + 1);
        if (found) return found;
      }
      return "";
    }
    if (typeof value === "object") {
      for (const key of ["url", "image_url", "audio_url", "audio", "image", "b64_json", "audio_base64"]) {
        const item = value[key];
        if (typeof item === "string" && item.trim()) {
          if (key === "b64_json" && !item.startsWith("data:")) return "data:image/png;base64," + item;
          if (key === "audio_base64" && !item.startsWith("data:")) return "data:audio/mpeg;base64," + item;
          const found = findMediaUrl(item, depth + 1);
          if (found) return found;
        }
      }
      for (const item of Object.values(value)) {
        const found = findMediaUrl(item, depth + 1);
        if (found) return found;
      }
    }
    return "";
  }

  function renderResult(host, action, responseData) {
    host.replaceChildren();
    const result = responseData?.result ?? responseData;
    const mediaUrl = findMediaUrl(result, 0);

    if (action === "image" && mediaUrl && /^(https:\/\/|data:image\/)/i.test(mediaUrl)) {
      const image = document.createElement("img");
      image.src = mediaUrl;
      image.alt = "Image generated by Free.ai";
      image.loading = "lazy";
      image.className = "de-media-result-image";
      host.appendChild(image);
    } else if (action === "tts" && mediaUrl && /^(https:\/\/|data:audio\/)/i.test(mediaUrl)) {
      const audio = document.createElement("audio");
      audio.controls = true;
      audio.preload = "metadata";
      audio.src = mediaUrl;
      audio.className = "de-media-result-audio";
      host.appendChild(audio);
    }

    const outputText = findOutputText(result);
    if (outputText) {
      appendText(host, "pre", outputText, "de-media-result-text");
    } else {
      appendText(host, "pre", JSON.stringify(result, null, 2), "de-media-result-text");
    }

    if (mediaUrl && /^https:\/\//i.test(mediaUrl)) {
      const link = document.createElement("a");
      link.href = mediaUrl;
      link.target = "_blank";
      link.rel = "noopener noreferrer";
      link.textContent = "Open generated media";
      link.className = "de-media-result-link";
      host.appendChild(link);
    }
  }

  function open() {
    const panel = document.getElementById("experience-panel");
    const body = document.getElementById("panel-body");
    if (!panel || !body) return;

    const token = getAuthToken();
    setPanelText("panel-kicker", "DREAM AI LAB · MEDIA STUDIO");
    setPanelText("panel-title", "Create and convert media.");
    setPanelText("panel-description", "Use Free.ai for image generation, translation and questions, or FreeTTS for natural spoken lesson notes and text.");

    if (!token) {
      body.innerHTML = '<article class="panel-card"><h3>Sign in required</h3><p>Sign in to use Media Studio through your Dream Education account.</p><button class="panel-action" type="button" data-panel-action="signin">Sign in</button></article>';
      document.body.classList.add("panel-open");
      panel.setAttribute("aria-hidden", "false");
      return;
    }

    body.innerHTML = `
      <section class="de-media-studio">
        <div class="de-media-mode-grid" role="group" aria-label="Media action">
          <label class="de-media-field">Tool
            <select id="de-media-action" class="panel-input">
              <option value="image">Text → Image</option>
              <option value="tts">Free.ai · Text → Speech</option>
              <option value="freetts">FreeTTS · Natural speech + subtitles</option>
              <option value="translate">Translate text</option>
              <option value="chat">Ask Free.ai</option>
            </select>
          </label>
          <label class="de-media-field" id="de-media-target-wrap" hidden>Target language
            <input id="de-media-target" class="panel-input" value="en" maxlength="16" placeholder="e.g. sw">
          </label>
        </div>
        <label class="de-media-field" id="de-media-prompt-label">Describe the image
          <textarea id="de-media-input" class="panel-input de-media-input" rows="5" maxlength="4000" placeholder="A clear, detailed description…"></textarea>
        </label>
        <p class="de-media-note">FreeTTS creates an MP3 and synchronized SRT subtitles. The FreeTTS key stays on the server. Provider limits apply; free-tier usage and commercial-use restrictions are set by FreeTTS.</p>
        <div class="panel-actions">
          <button class="panel-action" id="de-media-submit" type="button">Create</button>
          <button class="panel-action secondary" id="de-media-clear" type="button">Clear result</button>
        </div>
        <p class="de-media-status" id="de-media-status" role="status" aria-live="polite"></p>
        <div class="de-media-result" id="de-media-result" aria-live="polite"></div>
      </section>
    `;

    const actionSelect = body.querySelector("#de-media-action");
    const input = body.querySelector("#de-media-input");
    const promptLabel = body.querySelector("#de-media-prompt-label");
    const targetWrap = body.querySelector("#de-media-target-wrap");
    const targetInput = body.querySelector("#de-media-target");
    const submit = body.querySelector("#de-media-submit");
    const clear = body.querySelector("#de-media-clear");
    const status = body.querySelector("#de-media-status");
    const result = body.querySelector("#de-media-result");

    function updateMode() {
      const mode = actionSelect.value;
      targetWrap.hidden = mode !== "translate";
      promptLabel.firstChild.textContent = mode === "image" ? "Describe the image" :
        mode === "tts" || mode === "freetts" ? "Text to speak" :
        mode === "translate" ? "Text to translate" : "Question or instruction";
      input.placeholder = mode === "image" ? "A bright, detailed illustration of the water cycle…" :
        mode === "tts" || mode === "freetts" ? "Paste lesson notes or any text you want spoken aloud…" :
        mode === "translate" ? "Paste text to translate…" : "Ask a question…";
      submit.textContent = mode === "image" ? "Generate image" :
        mode === "tts" || mode === "freetts" ? "Generate speech" :
        mode === "translate" ? "Translate" : "Ask Free.ai";
    }

    actionSelect.addEventListener("change", updateMode);
    updateMode();

    submit.addEventListener("click", async function () {
      const action = actionSelect.value;
      const value = input.value.trim();
      if (!value) {
        status.textContent = "Enter some text first.";
        return;
      }
      submit.disabled = true;
      status.textContent = "Working…";
      result.replaceChildren();
      try {
        const response = await fetch("/api/media-studio/generate", {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: "Bearer " + token
          },
          body: JSON.stringify({
            action,
            prompt: action === "image" ? value : undefined,
            text: action === "image" ? undefined : value,
            target: targetInput.value.trim() || "en",
            voice: "en-US-JennyNeural",
            rate: "+0%",
            pitch: "+0Hz"
          })
        });
        const data = await response.json().catch(() => ({}));
        if (!response.ok || !data.success) {
          throw new Error(data.error || "Free.ai request failed.");
        }
        renderResult(result, action, data);
        status.textContent = action === "freetts" ? "Speech and subtitle files are ready. Audio links expire after one hour." : "Request completed by Free.ai.";
      } catch (error) {
        status.textContent = error.message || "Media request failed.";
      } finally {
        submit.disabled = false;
      }
    });

    clear.addEventListener("click", function () {
      result.replaceChildren();
      status.textContent = "";
    });

    document.body.classList.add("panel-open");
    panel.setAttribute("aria-hidden", "false");
  }

  window.DreamMediaStudio = { open };
})();
